# Regenerate src/ui-touch/emoji_mono_16.c: the T-Deck Max's monochrome emoji
# (EINK_V2), one glyph for every codepoint baked in src/ui-touch/emoji_data.c.
# Needs python3 with fontTools, and node (npx fetches lv_font_conv 1.5.2).
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT
curl -sSfL -o "$WORK/NotoEmoji.ttf" \
  "https://raw.githubusercontent.com/google/fonts/main/ofl/notoemoji/NotoEmoji%5Bwght%5D.ttf"
python3 -m fontTools.varLib.instancer "$WORK/NotoEmoji.ttf" wght=600 -o "$WORK/NotoEmoji-600.ttf"
CPS="$(python3 - "$ROOT/src/ui-touch/emoji_data.c" <<'PY'
import re, sys
s = open(sys.argv[1]).read()
print(','.join(hex(c) for c in sorted(set(int(m, 16) for m in re.findall(r'\{\s*0x([0-9a-fA-F]+)u?,\s*&d_', s)))))
PY
)"
npx -y lv_font_conv@1.5.2 --font "$WORK/NotoEmoji-600.ttf" --size 16 --bpp 4 --format lvgl \
  --no-compress -r "$CPS" -o "$WORK/emoji_mono_16.c"
python3 - "$WORK/emoji_mono_16.c" "$ROOT/src/ui-touch/emoji_mono_16.c" <<'PY'
import sys
s = open(sys.argv[1]).read()
body = s[s.index('#if EMOJI_MONO_16\n') + len('#if EMOJI_MONO_16\n'):]
body = body.replace('#endif /*#if EMOJI_MONO_16*/', '#endif /* HAS_TDECK_MAX */')
hdr = """/*******************************************************************************
 * Size: 16 px
 * Bpp: 4
 * Monochrome emoji for the T-Deck Max's e-paper panel (EINK_V2): the same
 * codepoints as emoji_data.c, as an ordinary bitmap font so they take the text
 * colour (white in a black bubble) instead of thresholding colour art to blobs.
 * Generated by scripts/build/gen-emoji-mono.sh with lv_font_conv 1.5.2 from
 * Noto Emoji (monochrome, SIL OFL 1.1), instanced at weight 600.
 ******************************************************************************/

#include "lvgl.h"

#if defined(HAS_TDECK_MAX)
"""
open(sys.argv[2], 'w').write(hdr + body)
PY
echo "wrote src/ui-touch/emoji_mono_16.c"
